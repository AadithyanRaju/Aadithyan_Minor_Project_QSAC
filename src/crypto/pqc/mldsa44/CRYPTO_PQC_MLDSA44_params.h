/**
 * @file CRYPTO_PQC_MLDSA44_params.h
 * @brief Parameter definitions for ML-DSA-44 (Dilithium-2 / NIST Security Category 2).
 */

#ifndef CRYPTO_PQC_MLDSA44_PARAMS_H
#define CRYPTO_PQC_MLDSA44_PARAMS_H

#define DILITHIUM_K 4
#define DILITHIUM_L 4
#define DILITHIUM_N 256
#define DILITHIUM_Q 8380417
#define DILITHIUM_D 13
#define DILITHIUM_ROOT_OF_UNITY 1753

#define DILITHIUM_SEEDBYTES 32
#define DILITHIUM_CRHBYTES  64
#define DILITHIUM_TRBYTES   64
#define DILITHIUM_RNDBYTES  32

#define DILITHIUM_GAMMA1 (1 << 17)
#define DILITHIUM_GAMMA2 ((DILITHIUM_Q - 1) / 88)
#define DILITHIUM_BETA   78
#define DILITHIUM_ETA    2
#define DILITHIUM_TAU    39
#define DILITHIUM_OMEGA  80

#define DILITHIUM_POLYT1_PACKEDBYTES 320
#define DILITHIUM_POLYT0_PACKEDBYTES 416
#define DILITHIUM_POLYVECH_PACKEDBYTES (DILITHIUM_OMEGA + DILITHIUM_K)
#define DILITHIUM_POLYZ_PACKEDBYTES   576
#define DILITHIUM_POLYW1_PACKEDBYTES  192
#define DILITHIUM_POLYETA_PACKEDBYTES 96

#define DILITHIUM_PUBLICKEYBYTES  (DILITHIUM_SEEDBYTES + DILITHIUM_K * DILITHIUM_POLYT1_PACKEDBYTES)
#define DILITHIUM_SECRETKEYBYTES  (2 * DILITHIUM_SEEDBYTES + DILITHIUM_TRBYTES + DILITHIUM_L * DILITHIUM_POLYETA_PACKEDBYTES + DILITHIUM_K * DILITHIUM_POLYETA_PACKEDBYTES + DILITHIUM_K * DILITHIUM_POLYT0_PACKEDBYTES)
#define DILITHIUM_SIGNATUREBYTES  (DILITHIUM_SEEDBYTES + DILITHIUM_L * DILITHIUM_POLYZ_PACKEDBYTES + DILITHIUM_POLYVECH_PACKEDBYTES)

#endif /* CRYPTO_PQC_MLDSA44_PARAMS_H */
