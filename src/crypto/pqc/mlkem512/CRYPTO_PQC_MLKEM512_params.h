/**
 * @file CRYPTO_PQC_MLKEM512_params.h
 * @brief Parameter definitions for ML-KEM-512 (Kyber-512).
 */

#ifndef CRYPTO_PQC_MLKEM512_PARAMS_H
#define CRYPTO_PQC_MLKEM512_PARAMS_H

#define KYBER_K 2
#define KYBER_N 256
#define KYBER_Q 3329

#define KYBER_ETA1 3
#define KYBER_ETA2 2

#define KYBER_DU 10
#define KYBER_DV 4

#define KYBER_SYMBYTES 32
#define KYBER_SSBYTES  32

#define KYBER_POLYBYTES 384
#define KYBER_POLYVECBYTES (KYBER_K * KYBER_POLYBYTES)

#define KYBER_POLYVECCOMPRESSEDBYTES_DU (KYBER_K * 320)
#define KYBER_POLYCOMPRESSEDBYTES_DV    128

#define KYBER_INDCPA_MSGBYTES       (KYBER_SYMBYTES)
#define KYBER_INDCPA_PUBLICKEYBYTES (KYBER_POLYVECBYTES + KYBER_SYMBYTES)
#define KYBER_INDCPA_SECRETKEYBYTES (KYBER_POLYVECBYTES)
#define KYBER_INDCPA_BYTES          (KYBER_POLYVECCOMPRESSEDBYTES_DU + KYBER_POLYCOMPRESSEDBYTES_DV)

#define KYBER_PUBLICKEYBYTES  (KYBER_INDCPA_PUBLICKEYBYTES)
#define KYBER_SECRETKEYBYTES  (KYBER_INDCPA_SECRETKEYBYTES + KYBER_INDCPA_PUBLICKEYBYTES + 2 * KYBER_SYMBYTES)
#define KYBER_CIPHERTEXTBYTES (KYBER_INDCPA_BYTES)

#endif /* CRYPTO_PQC_MLKEM512_PARAMS_H */
